import type { DbCategory, DbRecord } from "../types";

function record(
  key: string,
  category: DbCategory,
  title: string,
  keywords: string[],
  facts: [field: string, label: string, value: string][],
  body?: string,
): DbRecord {
  return {
    id: `g-${key}`,
    category,
    title,
    keywords,
    facts: facts.map(([field, label, value]) => ({ id: `g.w.${key}.${field}`, label, value })),
    body,
  };
}

