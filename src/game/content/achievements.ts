import type { Achievement, DecisionRecord, RunOutcome } from "../types";
import { post } from "./templateVars";

type Condition = Achievement["condition"];
type Ctx = Parameters<Condition>[0];

const always = () => true;

const runEnded =
  (outcome: RunOutcome, pred: (c: Ctx) => boolean = always): Condition =>
  (c) =>
    c.event.type === "runEnded" && c.event.outcome === outcome && pred(c);

/** Honeypotted by a named spy. Only these achievements may use {spyName}. */
const spyEnded = (pred: (c: Ctx) => boolean = always): Condition =>
  runEnded("honeypotted", (c) => c.stats.fatalSpyName !== undefined && pred(c));

const decided =
  (pred: (d: DecisionRecord, investigated: number, c: Ctx) => boolean): Condition =>
  (c) =>
    c.event.type === "decided" && pred(c.event.decision, c.event.investigated, c);

const eggFound =
  (eggId: string): Condition =>
  (c) =>
    c.event.type === "eggFound" && c.event.eggId === eggId;

const lifetimeEggs = (c: Ctx) => new Set([...c.profile.eggsFound, ...c.stats.eggsFound]).size;
const marketCapLost = (c: Ctx) => c.stats.startingMarketCap - c.stats.marketCap;
const spiesCaughtOnDay = (c: Ctx, day: number) =>
  c.stats.decisions.filter((d) => d.day === day && d.truth === "spy" && d.verdict === "reject").length;

